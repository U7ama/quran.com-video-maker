export const hash = value => createHash('sha256').update(value).digest('hex');
export const seed = value => parseInt(hash(value).slice(0, 8), 16);

export function chooseFromCatalogue(date, history, ids) {
  const recent = new Set(history.slice(-6).map(item => item.passageId));
  const pool = PASSAGES.filter(p => !recent.has(p.id));
  const passage = (pool.length ? pool : PASSAGES)[seed(date) % (pool.length || PASSAGES.length)];
  return {passageId: passage.id, translationId: ids[seed(date + 'translation') % ids.length],
    theme: THEMES[seed(date + 'background') % THEMES.length], selector:'catalogue'};
}

export function validateSelection(input, allowedTranslationIds) {
  if (!input || !PASSAGES.some(p => p.id === input.passageId)) throw new Error('Selector chose an unapproved passage');
  if (!allowedTranslationIds.includes(input.translationId)) throw new Error('Selector chose an unapproved translation');
  if (!THEMES.includes(input.theme)) throw new Error('Selector chose an unapproved background theme');
  // Nothing generated by the model, other than these identifiers, reaches the video.
  return {passageId:input.passageId, translationId:input.translationId, theme:input.theme};
}

export function plainTranslation(text) {
  const entities = {amp:'&', lt:'<', gt:'>', quot:'"', apos:"'", nbsp:' ', rsquo:'’', lsquo:'‘', rdquo:'”', ldquo:'“', hellip:'…'};
  return text.replace(/<sup\b[^>]*>[\s\S]*?<\/sup>/gi, '')
    .replace(/<br\s*\/?>/gi, '\n').replace(/<[^>]+>/g, '')
    .replace(/&(#x[0-9a-f]+|#\d+|[a-z]+);/gi, (match, entity) => {
      if (entity.startsWith('#x')) return String.fromCodePoint(parseInt(entity.slice(2), 16));
      if (entity.startsWith('#')) return String.fromCodePoint(Number(entity.slice(1)));
      if (entities[entity] !== undefined) return entities[entity];
      throw new Error(`Unsupported translation entity ${entity}`);
    }).trim();
}

export function validateContent(payload, audio, passage, translationId) {
  if (!payload || !Array.isArray(payload.verses) || payload.verses.length !== passage.to - passage.from + 1) {
    throw new Error('Incomplete verse response; refusing to publish');
  }
  if (!audio || audio.chapter_id !== passage.chapter || !Array.isArray(audio.verse_timings)) {
    throw new Error('Wrong chapter audio or missing recitation timings');
  }
  const cues = payload.verses.map((verse, index) => {
    const key = `${passage.chapter}:${passage.from + index}`;
    if (verse.verse_key !== key || verse.chapter_id !== passage.chapter ||
        !verse.text_uthmani || !/[\u0600-\u06ff]/u.test(verse.text_uthmani)) {
      throw new Error('Missing Arabic text or non-consecutive verses');
    }
    const translations = verse.translations || [];
    const translation = translations.find(t => Number(t.resource_id) === translationId);
    if (!translation || typeof translation.text !== 'string' || !translation.text.trim()) {
      throw new Error(`Missing verified translation for ${key}`);
    }
    const timing = audio.verse_timings.find(t => t.verse_key === key);
    if (!timing || !Number.isFinite(timing.timestamp_from) || !Number.isFinite(timing.timestamp_to) ||
        timing.timestamp_to <= timing.timestamp_from || timing.timestamp_from < 0) {
      throw new Error(`Invalid recitation timing for ${key}`);
    }
    const text = plainTranslation(translation.text);
    if (text.length > 700 || verse.text_uthmani.length > 500) throw new Error('Text exceeds readable layout limits');
    return {key, arabic:verse.text_uthmani.trim(), translation:text,
      fromMs:timing.timestamp_from, toMs:timing.timestamp_to};
  });
  for (let i = 1; i < cues.length; i++) {
    if (cues[i].fromMs < cues[i-1].toMs - 80 || cues[i].fromMs - cues[i-1].toMs > 3000) {
      throw new Error('Overlapping or discontinuous recitation timings');
    }
  }
  return cues;
}

export function makeTimeline(cues, fps = 24) {
  const startMs = cues[0].fromMs;
  const endMs = cues.at(-1).toMs;
  const intro = Math.round(fps * 1.5);
  const audioFrames = Math.ceil((endMs - startMs) * fps / 1000);
  return {startMs, endMs, fps, intro, durationInFrames:intro + audioFrames + fps,
    cues:cues.map((cue, index) => ({...cue,
      fromFrame: index === 0 ? 0 : intro + Math.round((cue.fromMs - startMs) * fps / 1000),
      toFrame:index === cues.length - 1 ? intro + audioFrames + fps
        : intro + Math.round((cues[index + 1].fromMs - startMs) * fps / 1000),
    }))};
}

export const STOCK_PROVIDERS={
  pexels:{name:'Pexels',license:'Pexels License',licenseUrl:'https://www.pexels.com/license/',
    homepage:'https://www.pexels.com',host:'www.pexels.com',path:'/video/'},
  pixabay:{name:'Pixabay',license:'Pixabay Content License',licenseUrl:'https://pixabay.com/service/license-summary/',
    homepage:'https://pixabay.com',host:'pixabay.com',path:'/videos/'},
};

export function backgroundKey(entry) {
  if(!STOCK_PROVIDERS[entry?.provider] || !/^\d+$/.test(String(entry?.id))) throw new Error('Invalid background identity');
  return `${entry.provider}-${entry.id}`;
}

export function isStockSource(provider,value) {
  try {
    const expected=STOCK_PROVIDERS[provider];
    const url=new URL(value);
    return Boolean(expected && url.protocol==='https:' && url.hostname===expected.host &&
      !url.username && !url.password && !url.port && url.pathname.startsWith(expected.path));
  } catch {return false;}
}

function validStockMetadata(entry) {
  const provider=STOCK_PROVIDERS[entry?.provider];
  return Boolean(entry && provider && /^\d+$/.test(String(entry.id)) &&
      entry.license === provider.license && isStockSource(entry.provider,entry.sourceUrl) &&
      (!entry.licenseUrl || entry.licenseUrl===provider.licenseUrl) &&
      (entry.provider!=='pixabay' || entry.licenseUrl===provider.licenseUrl) &&
      (!entry.key || entry.key===backgroundKey(entry)) &&
      /^[a-f0-9]{64}$/.test(entry.sha256) && THEMES.includes(entry.theme));
}

export function validateBackground(entry) {
  if (!validStockMetadata(entry) || entry.approved !== true || !entry.reviewedAt) {
    throw new Error('Unreviewed or unlicensed background rejected');
  }
  return entry;
}

export function validateScreenedBackground(entry) {
  if (!validStockMetadata(entry) || entry.provider!=='pixabay' || entry.approved!==false ||
      entry.reviewMode!=='automated-metadata' || !entry.screenedAt || entry.safeSearch!==true || entry.type!=='film') {
    throw new Error('Invalid automatically screened background');
  }
  return entry;
}

export function deliveryAction(state) {
  if (state.status === 'delivered') return 'skip';
  if (['sending', 'uncertain'].includes(state.status)) return 'hold';
  return 'send';
}
