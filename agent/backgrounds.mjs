import {mkdir, copyFile, readFile, rm} from 'node:fs/promises';
import path from 'node:path';
import {THEMES, seed, hash, validateBackground, validateScreenedBackground, STOCK_PROVIDERS, backgroundKey, isStockSource} from './core.mjs';
import {getJson, download, writeJson, readJson, fileHash, command, probe, isFile, assertMediaUrl} from './io.mjs';
import {fallbackBackground} from './builtin-backgrounds.mjs';

const MAX_DOWNLOAD=70*1024*1024;
const CACHE_MS=24*60*60*1000;
const defaults={getJson,download,probe,command,now:()=>Date.now()};

export async function chooseBackground(config, theme, date, assetDir, overrides={}) {
  if(config.backgroundMode==='daily') {
    let selected;
    try {selected=await chooseDailyBackground(config,theme,date,assetDir,overrides);}
    catch {return fallbackBackground(config,theme,date,assetDir,'Saved stock unavailable or failed validation');}
    if(selected.kind==='generated')return fallbackBackground(config,theme,date,assetDir,selected.fallbackReason);
    return selected;
  }
  if (config.backgroundMode !== 'generated') {
    const manifest = await readJson(path.join(config.dataDir,'backgrounds','approved.json'), []);
    const available=manifest.filter(item=>item.provider===(config.backgroundProvider || 'pixabay'));
    const pool = available.filter(item=>item.theme===theme);
    const choices = pool.length ? pool : available;
    if (choices.length) {
      const entry = validateBackground(choices[seed(date) % choices.length]);
      let source=path.join(config.dataDir,'backgrounds','approved',`${backgroundKey(entry)}.mp4`);
      // Retain previously approved Pexels libraries without confusing numeric IDs across providers.
      if(entry.provider==='pexels' && !await isFile(source)) {
        source=path.join(config.dataDir,'backgrounds','approved',`${entry.id}.mp4`);
      }
      if (await fileHash(source) !== entry.sha256) throw new Error('Approved background changed after review');
      await mkdir(assetDir,{recursive:true,mode:0o700});
      await command('ffmpeg', ['-hide_banner','-loglevel','error','-y','-i',source,'-an','-c:v','copy',path.join(assetDir,'background.mp4')]);
      return {...entry, src:`/agent-cache/${path.basename(assetDir)}/background.mp4`, kind:'video'};
    }
    if (config.backgroundMode === 'approved') throw new Error('No reviewed stock backgrounds for the selected provider; approve a clip or use generated mode');
  }
  return {kind:'generated', theme, seed:seed(date), provider:'local', creator:'Daily Quran Agent',
    license:'Locally generated by this application', sourceUrl:null};
}

function quality(file) {
  // Rank by usable pixels after the portrait cover crop. A 4K landscape can
  // retain more detail than a low-resolution portrait; prefer native 1080p.
  const cropWidth=Math.min(file.width,file.height*9/16);
  return Math.max(0,Math.log(1080/cropWidth))*10 +
    Math.abs(Math.log((file.width/file.height)/(9/16)))*0.1 +
    Math.abs(Math.log(cropWidth/1080))*0.01;
}

export function normalizeCandidates(provider,result) {
  const videos=provider==='pixabay' ? result?.hits : result?.videos;
  if(!Array.isArray(videos)) throw new Error(`${STOCK_PROVIDERS[provider]?.name || 'Stock API'} response is missing video results`);
  return videos.flatMap(video=>{
    if(!video || !Number.isSafeInteger(video.id) || video.id<=0 || !Number.isFinite(video.duration) || video.duration<5 || video.duration>90) return [];
    const sourceUrl=provider==='pixabay' ? video.pageURL : video.url;
    if(!isStockSource(provider,sourceUrl))return [];
    const files=provider==='pixabay' ? Object.values(video.videos || {}) : (Array.isArray(video.video_files) ? video.video_files : []).filter(f=>f?.file_type==='video/mp4');
    const candidates=files.filter(file=>{
      if(!file || !Number.isInteger(file.width) || !Number.isInteger(file.height) || file.width<540 || file.width>3840 || file.height<540 || file.height>3840 || file.size>MAX_DOWNLOAD) return false;
      try {assertMediaUrl(file.url || file.link);return true;} catch {return false;}
    }).sort((a,b)=>quality(a)-quality(b));
    const file=candidates[0];
    if(!file)return [];
    return [{id:String(video.id),provider,sourceUrl,url:file.url || file.link,
      width:file.width,height:file.height,duration:video.duration,
      creator:String(provider==='pixabay' ? video.user || 'Pixabay contributor' : video.user?.name || 'Pexels contributor'),
      tags:typeof video.tags==='string' ? video.tags : '',type:video.type}];
  }).sort((a,b)=>quality(a)-quality(b));
}

async function searchPixabay(config,theme,deps,extra={}) {
  if(!config.pixabayKey)throw new Error('Set PIXABAY_API_KEY in agent/.env first');
  const parameters={q:`${theme} landscape scenery`,category:'nature',video_type:'film',safesearch:'true',
    min_width:'1080',min_height:'1080',per_page:'10',order:'popular',...extra};
  const cacheFile=path.join(config.dataDir,'backgrounds','cache',`pixabay-${hash(JSON.stringify(parameters))}.json`);
  const cache=await readJson(cacheFile,null);
  const age=deps.now()-cache?.fetchedAt;
  if(cache && Number.isFinite(age) && age>=0 && age<CACHE_MS && Array.isArray(cache.result?.hits))return cache.result;
  const url=new URL('https://pixabay.com/api/videos/');
  url.search=new URLSearchParams({...parameters,key:config.pixabayKey}).toString();
  // getJson reports only a label/status on failure: the key in this URL is never logged or cached.
  const result=await deps.getJson(url,{label:'Pixabay'});
  normalizeCandidates('pixabay',result);
  await writeJson(cacheFile,{fetchedAt:deps.now(),parameters,result});
  return result;
}

// Metadata screening is deliberately distinct from an entire-clip human review.
// SafeSearch and nature tags cannot establish that every frame is suitable.
const NATURE_TAG=/\b(?:mountain\w*|lake\w*|landscape\w*|forest\w*|woodland\w*|tree\w*|cloud\w*|sky|skies|ocean\w*|sea|waves?|waterfall\w*|river\w*|stream\w*|desert\w*|dunes?|stars?|starry|sunset\w*|sunrise\w*|snow|glacier\w*|nature|scenery|valley|valleys|water)\b/i;
const EXCLUDED_TAG=/\b(?:people|person\w*|human\w*|man|men|woman|women|child\w*|kids?|boy\w*|girl\w*|family|families|crowd\w*|tourist\w*|hiker\w*|hiking|climb\w*|swim\w*|surfer\w*|surfing|diver\w*|diving|fisher\w*|fishing|sail\w*|boat\w*|ship\w*|yacht\w*|animal\w*|wildlife|bird\w*|duck\w*|swan\w*|fish\w*|insect\w*|butterfl\w*|dog\w*|cat\w*|horse\w*|cow\w*|deer|sheep|lion\w*|tiger\w*|snake\w*|elephant\w*|monkey\w*|pet\w*|nud\w*|naked|sexy|bikini\w*|fashion|model\w*|dance\w*|dancing|music|concert\w*|party|parties|religio\w*|god\w*|allah|prophet\w*|angel\w*|paradise|heaven\w*|hell|miracle\w*|church\w*|temple\w*|mosque\w*|buddha\w*|shiva|vishnu|krishna|ganesh\w*|deity|deities|hindu\w*|idol\w*|statue\w*|cross|architecture|building\w*|castle\w*|museum\w*|historic\w*|city|cities|urban|street\w*|boulevard\w*|logo\w*|brand\w*|advert\w*|text|watermark\w*|casino\w*|gambl\w*|alcohol|wine|beer|drug\w*|smok\w*|firework\w*|war|weapon\w*|blood|death|disaster\w*|volcano\w*|eruption\w*)\b/i;

export function isNatureCandidate(candidate) {
  return candidate.provider==='pixabay' && candidate.type==='film' &&
    typeof candidate.tags==='string' && candidate.tags.length<=2000 &&
    NATURE_TAG.test(candidate.tags) && !EXCLUDED_TAG.test(candidate.tags);
}

function generatedBackground(theme,date,reason) {
  return {kind:'generated',theme,seed:seed(date),provider:'local',creator:'Daily Quran Agent',
    license:'Locally generated by this application',sourceUrl:null,fallbackReason:reason};
}

export async function chooseDailyBackground(config,theme,date,assetDir,overrides={}) {
  if(!THEMES.includes(theme) || !/^\d{4}-\d{2}-\d{2}$/.test(date))throw new Error('Invalid daily background request');
  if(config.backgroundProvider!=='pixabay')throw new Error('Daily fresh backgrounds require Pixabay');
  const deps={...defaults,...overrides};
  const directory=path.join(config.dataDir,'backgrounds');
  const ledgerFile=path.join(directory,'daily.json');
  const ledger=await readJson(ledgerFile,{runs:{},pages:{}});
  let entry=ledger.runs[date];
  const clip=path.join(directory,'daily',`${date}.mp4`);
  if(!entry) {
    const reviewed=await readJson(path.join(directory,'approved.json'),[]);
    const usedIds=new Set([...Object.values(ledger.runs),...reviewed].filter(e=>e.provider==='pixabay').map(e=>e.id));
    const usedHashes=new Set([...Object.values(ledger.runs),...reviewed].map(e=>e.sha256).filter(Boolean));
    const page=ledger.pages[theme] || 1;
    let result;
    try {
      // A bounded search once per local date; same-query responses remain cached 24h.
      result=await searchPixabay(config,theme,deps,{order:'latest',page:String(page)});
    } catch {
      entry=generatedBackground(theme,date,'Pixabay search unavailable');
    }
    if(result) {
      const lastPage=Math.max(1,Math.min(50,Math.ceil((Number(result.totalHits)||10)/10)));
      ledger.pages[theme]=page>=lastPage ? 1 : page+1;
      const candidates=normalizeCandidates('pixabay',result).filter(isNatureCandidate)
        .filter(c=>!usedIds.has(c.id)).slice(0,2);
      for(const candidate of candidates) {
        try {
          await mkdir(path.dirname(clip),{recursive:true,mode:0o700});
          await deps.download(candidate.url,clip,MAX_DOWNLOAD);
          const media=await deps.probe(clip);
          const video=media.streams?.find(s=>s.codec_type==='video');
          const duration=Number(media.format?.duration);
          if(!video || video.width!==candidate.width || video.height!==candidate.height ||
              !Number.isFinite(duration) || duration<5 || duration>90)continue;
          const sha256=await fileHash(clip);
          if(usedHashes.has(sha256))continue;
          entry={id:candidate.id,key:backgroundKey(candidate),provider:'pixabay',theme,
            sourceUrl:candidate.sourceUrl,creator:candidate.creator,tags:candidate.tags,type:candidate.type,
            license:STOCK_PROVIDERS.pixabay.license,licenseUrl:STOCK_PROVIDERS.pixabay.licenseUrl,
            sha256,duration,width:video.width,height:video.height,approved:false,
            reviewMode:'automated-metadata',safeSearch:true,screenedAt:new Date(deps.now()).toISOString(),kind:'video'};
          validateScreenedBackground(entry);
          break;
        } catch { /* Try at most one more filtered candidate; never expose request URLs or keys. */ }
      }
      entry ||= generatedBackground(theme,date,'No suitable unused Pixabay clip in the daily results');
    }
    ledger.runs[date]=entry;
    // Reserve a selection before rendering so retries cannot replace it or repeat searches.
    await writeJson(ledgerFile,ledger);
    if(entry.kind==='generated')await rm(clip,{force:true});
    // Keep IDs/checksums for repeat avoidance, but limit raw daily stock storage to seven dates.
    for(const oldDate of Object.keys(ledger.runs).sort().slice(0,-7)) {
      await rm(path.join(directory,'daily',`${oldDate}.mp4`),{force:true});
    }
  }
  if(entry.kind==='generated')return entry;
  validateScreenedBackground(entry);
  if(!isNatureCandidate(entry)) {
    const rejected=entry;
    entry={...generatedBackground(theme,date,'Saved clip no longer passes content screening'),
      rejectedSource:{id:rejected.id,provider:rejected.provider,sha256:rejected.sha256}};
    ledger.runs[date]=entry;
    await writeJson(ledgerFile,ledger);
    return entry;
  }
  if(await fileHash(clip)!==entry.sha256)throw new Error('Daily background changed after screening');
  await mkdir(assetDir,{recursive:true,mode:0o700});
  await deps.command('ffmpeg',['-hide_banner','-loglevel','error','-y','-i',clip,'-an','-c:v','copy',path.join(assetDir,'background.mp4')]);
  const silent=await deps.probe(path.join(assetDir,'background.mp4'));
  if(!silent.streams?.some(s=>s.codec_type==='video') || silent.streams.some(s=>s.codec_type==='audio'))throw new Error('Daily background audio removal failed');
  return {...entry,src:`/agent-cache/${path.basename(assetDir)}/background.mp4`};
}

export async function fetchBackgroundCandidates(config, theme, overrides={}) {
  if (!THEMES.includes(theme)) throw new Error(`Theme must be one of: ${THEMES.join(', ')}`);
  const deps={...defaults,...overrides};
  const provider=config.backgroundProvider || 'pixabay';
  if(!STOCK_PROVIDERS[provider])throw new Error('Unsupported background provider');
  let result;
  if(provider==='pixabay') result=await searchPixabay(config,theme,deps);
  else {
    if(!config.pexelsKey)throw new Error('Set PEXELS_API_KEY in agent/.env first');
    const url=new URL('https://api.pexels.com/v1/videos/search');
    url.search=new URLSearchParams({query:`${theme} landscape scenery`,orientation:'portrait',per_page:'5'}).toString();
    result=await deps.getJson(url,{headers:{Authorization:config.pexelsKey},label:'Pexels'});
  }
  const outputs=[];
  for(const candidate of normalizeCandidates(provider,result).slice(0,2)) {
    const key=backgroundKey(candidate);
    const folder=path.join(config.dataDir,'backgrounds','candidates',key);
    await mkdir(folder,{recursive:true,mode:0o700});
    const clip=path.join(folder,'video.mp4');
    // Existing local candidates need not be downloaded again when the API result is cached.
    const old=await readJson(path.join(folder,'metadata.json'),null);
    if(!old || old.sourceUrl!==candidate.sourceUrl || !await isFile(clip) || await fileHash(clip)!==old.sha256) {
      await deps.download(candidate.url,clip,MAX_DOWNLOAD);
    }
    const media=await deps.probe(clip);
    const duration=Number(media.format?.duration);
    if(!media.streams?.some(s=>s.codec_type==='video') || !Number.isFinite(duration) || duration<5 || duration>90)throw new Error('Stock clip has invalid video content or duration');
    const metadata={id:candidate.id,key,provider,theme,sourceUrl:candidate.sourceUrl,creator:candidate.creator,
      license:STOCK_PROVIDERS[provider].license,licenseUrl:STOCK_PROVIDERS[provider].licenseUrl,
      sha256:await fileHash(clip),duration,width:candidate.width,height:candidate.height,approved:false};
    await writeJson(path.join(folder,'metadata.json'),metadata);
    const preview=path.join(folder,'contact-sheet.jpg');
    // Pad short clips so even a five-second candidate produces a complete contact sheet.
    if(!await isFile(preview))await deps.command('ffmpeg',['-hide_banner','-loglevel','error','-y','-i',clip,
      '-vf','fps=1/5,scale=240:-1,tpad=stop_mode=clone:stop=16,tile=4x4','-frames:v','1',preview]);
    outputs.push({id:key,file:clip,preview,source:candidate.sourceUrl,license:metadata.licenseUrl});
  }
  return outputs;
}

export async function approveBackground(config, id, reviewed) {
  if(!reviewed || !/^(?:(?:pixabay|pexels)-)?\d+$/.test(id))throw new Error('View the entire clip and use --reviewed only after checking the content rules');
  const folder=path.join(config.dataDir,'backgrounds','candidates',id);
  const metadata=JSON.parse(await readFile(path.join(folder,'metadata.json'),'utf8'));
  const key=backgroundKey(metadata);
  if(id!==key && !(metadata.provider==='pexels' && id===metadata.id))throw new Error('Candidate identity does not match its metadata');
  if(await fileHash(path.join(folder,'video.mp4'))!==metadata.sha256)throw new Error('Candidate changed after download');
  const approved=validateBackground({...metadata,key,approved:true,reviewedAt:new Date().toISOString()});
  const target=path.join(config.dataDir,'backgrounds','approved');
  await mkdir(target,{recursive:true,mode:0o700});
  await copyFile(path.join(folder,'video.mp4'),path.join(target,`${key}.mp4`));
  const manifestFile=path.join(config.dataDir,'backgrounds','approved.json');
  const manifest=await readJson(manifestFile,[]);
  await writeJson(manifestFile,[...manifest.filter(item=>backgroundKey(item)!==key),approved]);
  return approved;
}
