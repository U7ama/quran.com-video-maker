import path from 'node:path';
import {seed} from './core.mjs';
import {writeJson} from './io.mjs';
import {inspectBackgroundVideo} from './background-inspection.mjs';
import {decideBackground} from './background-agent.mjs';
import {fallbackBackground} from './builtin-backgrounds.mjs';

export async function inspectionFallback(first, second, ...rest) {
  let config = {}, background, date, assetDir, reason = 'Background inspection requires a fallback';
  if(first && typeof first === 'object' && first.theme && (first.kind || first.provider)) {
    background = first;
    if(typeof second === 'string') reason = second;
    const opts = rest[0] || {};
    config = opts.config || {};
    date = opts.date;
    assetDir = opts.assetDir;
  } else {
    config = first || {};
    background = second;
    date = rest[0];
    assetDir = rest[1];
    if(typeof rest[2] === 'string') reason = rest[2];
  }
  if(assetDir && date && background?.theme) {
    const fallback = await fallbackBackground(config, background.theme, date, assetDir, reason);
    return {
      ...fallback,
      fallbackReason: reason,
      rejectedSource: {provider: background.provider, id: background.id, sha256: background.sha256},
      ...(background.inspection ? {inspection: background.inspection} : {})
    };
  }
  return {
    kind: 'generated',
    theme: background?.theme,
    seed: seed(`${background?.sha256 || background?.id || ''}:inspection`),
    provider: 'local',
    creator: 'Daily Quran Agent',
    license: 'Locally generated by this application',
    sourceUrl: null,
    fallbackReason: reason,
    rejectedSource: {provider: background?.provider, id: background?.id, sha256: background?.sha256},
    ...(background?.inspection ? {inspection: background.inspection} : {})
  };
}

export async function reviewChosenBackground(config,background,assetDir,folder,{analyzeFrame,inspect=inspectBackgroundVideo,decide=decideBackground,fetcher=fetch}={}) {
  if(config.backgroundInspection!=='rekognition' || background.kind!=='video')return background;
  let trace;
  try {
    const analyze=analyzeFrame || (await import('./cloud/rekognition.mjs')).analyzeFrame;
    trace=await decide(config,{candidateId:`${background.provider}-${background.id}`,
      inspect:()=>inspect(path.join(assetDir,'background.mp4'),{analyzeFrame:analyze})},fetcher);
  } catch {
    trace={mode:'policy-tool',modelCalls:0,toolCalls:[],decision:'fallback',error:'Background inspection unavailable'};
  }
  await writeJson(path.join(folder,'background-inspection.json'),trace);
  const inspected={...background,approved:background.approved===true,inspection:trace};
  if(trace.decision==='use' && trace.toolCalls?.[0]?.result?.status==='eligible') {
    return inspected;
  }
  const date=path.basename(folder);
  return await inspectionFallback(config,inspected,date,assetDir,'Background inspection flagged candidate; using bundled background');
}
