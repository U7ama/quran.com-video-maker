import path from 'node:path';
import {fileURLToPath} from 'node:url';
import {mkdir} from 'node:fs/promises';
import {seed} from './core.mjs';
import {fileHash,command,probe} from './io.mjs';

// Existing frontend assets only. The windmill clip is excluded from this preset.
export const BUILTIN_BACKGROUNDS=[
  {id:'stars',themes:['night sky']},
  {id:'sea',themes:['ocean']},
  {id:'nature',themes:['forest','clouds']},
  {id:'snow',themes:['mountains']},
  {id:'abstract',themes:['desert']},
];
const defaultDir=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'../quran.com-frontend-next/public/publicMin/videos');
export async function builtinBackground(config,theme,date,assetDir,reason) {
  const pool=BUILTIN_BACKGROUNDS.filter(x=>x.themes.includes(theme));
  const choices=pool.length ? pool : BUILTIN_BACKGROUNDS;
  const entry=choices[seed(date+'builtin')%choices.length];
  const source=path.join(config.builtinDir || defaultDir,`videos_${entry.id}.mp4`);
  await mkdir(assetDir,{recursive:true,mode:0o700});
  const target=path.join(assetDir,'background.mp4');
  await command('ffmpeg',['-hide_banner','-loglevel','error','-y','-i',source,'-an','-c:v','copy',target]);
  const media=await probe(target);
  const video=media.streams.find(x=>x.codec_type==='video');
  if(!video || Number(media.format.duration)<5 || media.streams.some(x=>x.codec_type==='audio'))throw new Error('Built-in background validation failed');
  return {kind:'video',provider:'builtin',id:entry.id,theme,creator:'Quran.com media maker',
    sourceUrl:'https://github.com/quran/quran.com-frontend-next',
    license:'Existing Quran.com media-maker asset; original attribution preserved',
    sha256:await fileHash(source),width:video.width,height:video.height,duration:Number(media.format.duration),
    approved:false,reviewMode:'bundled-catalogue',fallbackReason:reason,
    src:`/agent-cache/${path.basename(assetDir)}/background.mp4`};
}
export async function fallbackBackground(config,theme,date,assetDir,reason) {
  try {return await builtinBackground(config,theme,date,assetDir,reason);}
  catch {return {kind:'generated',theme,seed:seed(date),provider:'local',creator:'Daily Quran Agent',
    license:'Locally generated by this application',sourceUrl:null,fallbackReason:'Built-in background unavailable'};}
}
